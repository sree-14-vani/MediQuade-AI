# Mount Google Drive
drive.mount('/content/drive')

# Your MediQuade AI project folder
PROJECT_DIR = Path(
    "/content/drive/MyDrive/MediQuade_AI"
)

# Files to download
file_names = [
    "app.py",
    "requirements.txt",
    ".gitignore"
]

# Download files
for name in file_names:
    file_path = PROJECT_DIR / name

    if file_path.exists():
        print(f"Downloading {name}...")
        files.download(str(file_path))
    else:
        print(f"File not found: {name}")

print("Download process completed!")





