def tokenize_example(example):
    prompt_messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": str(example["question"])},
    ]
    full_messages = prompt_messages + [{"role": "assistant", "content": str(example["answer"])}]

    prompt_text = tokenizer.apply_chat_template(
        prompt_messages, tokenize=False, add_generation_prompt=True, enable_thinking=False
    )
    full_text = tokenizer.apply_chat_template(
        full_messages, tokenize=False, add_generation_prompt=False, enable_thinking=False
    )
    prompt_ids = tokenizer.encode(prompt_text, add_special_tokens=False)
    full_ids = tokenizer.encode(full_text, add_special_tokens=False)

    # Keep room for answer tokens even when a question is unusually long.
    if full_ids[:len(prompt_ids)] != prompt_ids:
        raise ValueError("Prompt tokens are not a prefix of the full chat sequence; check the chat template.")
    answer_ids = full_ids[len(prompt_ids):]
    prompt_budget = min(len(prompt_ids), MAX_LENGTH // 2)
    prompt_ids = prompt_ids[-prompt_budget:] if prompt_budget else []
    answer_budget = MAX_LENGTH - len(prompt_ids)
    answer_ids = answer_ids[:answer_budget]
    input_ids = prompt_ids + answer_ids
    labels = ([-100] * len(prompt_ids)) + answer_ids.copy()

    if not answer_ids:
        # Avoid examples whose answer is entirely truncated.
        labels = [-100] * len(input_ids)

    return {
        "input_ids": [int(x) for x in input_ids],
        "attention_mask": [1] * len(input_ids),
        "labels": [int(x) for x in labels],
    }

